fn main() {
    generate_material_icons();

    #[cfg(windows)]
    {
        println!("cargo:rerun-if-changed=assets/favicon.ico");
        let mut res = winresource::WindowsResource::new();
        res.set_icon("assets/favicon.ico");
        if let Err(e) = res.compile() {
            println!("cargo:warning=failed to embed Windows icon: {e}");
        }
        stage_bundled_conpty();
    }
}

/// Turn the vendored Material Icon Theme into Rust the crate can `include!`.
///
/// The theme ships one JSON file that names an icon *id* for every file name,
/// extension and folder name it knows, plus a table of ids to svgs. Both are
/// resolved here so the app only ever deals with `name -> "icons/material/*.svg"`,
/// and so the glyphs are `include_bytes!`d instead of read from disk: a packaged
/// build has no `assets/` directory next to the executable.
///
/// Written to `OUT_DIR` rather than the source tree so a checkout stays free of
/// the ~13k line table this produces, and so bumping the theme is a matter of
/// dropping in the new `icons/` and `material-icons.json`.
fn generate_material_icons() {
    use std::collections::BTreeMap;
    use std::fmt::Write as _;
    use std::path::Path;

    const DIR: &str = "assets/icons/material";
    // The directory, not just the JSON: the svgs are what `include_bytes!`
    // reaches for, and a new theme drops in as a whole.
    println!("cargo:rerun-if-changed={DIR}");

    let theme_path = Path::new(DIR).join("material-icons.json");
    let theme: serde_json::Value = std::fs::read(&theme_path)
        .ok()
        .and_then(|bytes| serde_json::from_slice(&bytes).ok())
        .unwrap_or_else(|| {
            panic!(
                "{} is missing or unreadable; the vendored Material Icon Theme (MIT, see \
                 {DIR}/LICENSE) is what the file tree's icons are drawn from",
                theme_path.display()
            )
        });

    // Icon id to the svg `iconPath` names, e.g. "git" -> "icons/material/git.svg".
    let mut paths: BTreeMap<String, String> = BTreeMap::new();
    for (id, definition) in theme["iconDefinitions"].as_object().into_iter().flatten() {
        let Some(file) = definition["iconPath"]
            .as_str()
            .and_then(|path| path.rsplit('/').next())
        else {
            continue;
        };
        paths.insert(id.clone(), format!("icons/material/{file}"));
    }

    // A name table keyed lowercase (the theme has no two names that differ only
    // by case) plus, for file names, the handful of deliberately uppercase
    // entries the theme itself matches before it stops caring about case.
    let folded = |key: &str| -> BTreeMap<String, String> {
        let mut table = BTreeMap::new();
        for (name, id) in theme[key].as_object().into_iter().flatten() {
            let Some(path) = id.as_str().and_then(|id| paths.get(id)) else {
                continue;
            };
            table
                .entry(name.to_lowercase())
                .or_insert_with(|| path.clone());
        }
        table
    };
    let exact = |key: &str| -> BTreeMap<String, String> {
        let mut table = BTreeMap::new();
        for (name, id) in theme[key].as_object().into_iter().flatten() {
            if name.to_lowercase() == *name {
                continue;
            }
            let Some(path) = id.as_str().and_then(|id| paths.get(id)) else {
                continue;
            };
            table.entry(name.clone()).or_insert_with(|| path.clone());
        }
        table
    };

    let mut out =
        String::from("// @generated by build.rs from assets/icons/material; do not edit.\n");

    let mut glyphs: Vec<String> = std::fs::read_dir(DIR)
        .unwrap_or_else(|e| panic!("cannot read {DIR}: {e}"))
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".svg"))
        .collect();
    glyphs.sort();
    out.push_str("\nstatic FILES: &[(&str, &[u8])] = &[\n");
    for file in &glyphs {
        writeln!(
            out,
            r#"    ("icons/material/{file}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/{DIR}/{file}"))),"#
        )
        .unwrap();
    }
    out.push_str("];\n");

    emit_table(&mut out, "FILE_NAMES_EXACT", &exact("fileNames"));
    emit_table(&mut out, "FILE_NAMES", &folded("fileNames"));
    emit_table(&mut out, "FILE_EXTENSIONS", &folded("fileExtensions"));
    emit_table(&mut out, "FOLDER_NAMES", &folded("folderNames"));
    emit_table(
        &mut out,
        "FOLDER_NAMES_OPEN",
        &folded("folderNamesExpanded"),
    );

    for (name, key) in [
        ("DEFAULT_FILE", "file"),
        ("DEFAULT_FOLDER", "folder"),
        ("DEFAULT_FOLDER_OPEN", "folderExpanded"),
    ] {
        let path = theme[key]
            .as_str()
            .and_then(|id| paths.get(id))
            .unwrap_or_else(|| panic!("the theme names no {key} icon"));
        writeln!(out, "\nstatic {name}: &str = {path:?};").unwrap();
    }

    let destination = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"))
        .join("material_icons.rs");
    std::fs::write(&destination, out)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", destination.display()));
}

/// One sorted `&[(&str, &str)]` for `material_icons::lookup` to binary search.
fn emit_table(out: &mut String, name: &str, table: &std::collections::BTreeMap<String, String>) {
    use std::fmt::Write as _;

    writeln!(out, "\nstatic {name}: &[(&str, &str)] = &[").unwrap();
    for (key, path) in table {
        writeln!(out, "    ({key:?}, {path:?}),").unwrap();
    }
    out.push_str("];\n");
}

/// Put the bundled ConPTY beside cargo's output, the way the packaged app has
/// it beside `tty7-app.exe`.
///
/// `portable-pty` picks a sideloaded `conpty.dll` over the one in `kernel32`,
/// and finds it through the DLL search path — which starts at the directory of
/// the running executable, not the working directory. Without this a
/// development build silently runs on the in-box `conhost.exe` and loses the
/// `OSC 11` answer that packaged builds give (see `assets/windows/conpty`), so
/// the bug reappears only for people running from source.
///
/// Test executables live one directory deeper, so `deps/` gets a copy too.
#[cfg(windows)]
fn stage_bundled_conpty() {
    use std::path::{Path, PathBuf};

    println!("cargo:rerun-if-changed=assets/windows/conpty");

    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let vendored = match arch.as_str() {
        "x86_64" => "x64",
        "aarch64" => "arm64",
        // 32-bit Windows is unreleased, so nothing is vendored for it and the
        // in-box conhost stays in charge.
        _ => return,
    };
    let source = PathBuf::from("assets/windows/conpty").join(vendored);

    // .../target/<triple>?/<profile>/build/<pkg>-<hash>/out
    let Some(target_dir) = std::env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .and_then(|out| out.ancestors().nth(3).map(Path::to_path_buf))
    else {
        return;
    };

    for name in ["conpty.dll", "OpenConsole.exe"] {
        let from = source.join(name);
        for directory in [target_dir.clone(), target_dir.join("deps")] {
            if !directory.is_dir() {
                continue;
            }
            let to = directory.join(name);
            // Watching the destination as well as the source is what makes the
            // staging self-healing: cargo treats a path that no longer exists
            // as changed, so a copy that gets cleaned out of the target
            // directory comes back on the next build instead of staying gone
            // behind a cached build script.
            println!("cargo:rerun-if-changed={}", to.display());
            // Re-copying would fail while a previously built tty7 is running,
            // and the pair only changes when it is deliberately updated.
            let same = std::fs::metadata(&to)
                .ok()
                .zip(std::fs::metadata(&from).ok())
                .is_some_and(|(a, b)| a.len() == b.len());
            if same {
                continue;
            }
            if let Err(e) = std::fs::copy(&from, &to) {
                println!(
                    "cargo:warning=could not stage {}: {e} — this build will use the in-box conhost",
                    to.display()
                );
            }
        }
    }
}
